// Builds the dotted world map behind "The story so far" (src/data/worldmap.ts).
// Run with: npm run map   (only needed if the crop or dot spacing changes)
//
// Samples Natural Earth land (world-atlas, 110m) on a regular lon/lat grid and keeps
// a dot wherever there's land. The site ships only the resulting SVG path, not the data.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);

// Crop: the Americas to India and a little beyond (equirectangular)
const LON0 = -135;
const LON1 = 135;
const LAT0 = 64;
const LAT1 = -4;
const STEP = 1.5; // degrees between dots

const cols = Math.round((LON1 - LON0) / STEP);
const rows = Math.round((LAT0 - LAT1) / STEP);
let d = '';
let n = 0;
for (let r = 0; r <= rows; r++) {
  for (let c = 0; c <= cols; c++) {
    const lon = LON0 + c * STEP;
    const lat = LAT0 - r * STEP;
    if (geoContains(land, [lon, lat])) {
      d += `M${c} ${r}h0`;
      n++;
    }
  }
}

writeFileSync(
  'src/data/worldmap.ts',
  `// Generated by scripts/make-map.mjs. Do not edit by hand.
// Grid units: one unit = ${STEP}° (equirectangular), origin at ${LON0}°, ${LAT0}°.
export const MAP = {
  lon0: ${LON0},
  lat0: ${LAT0},
  step: ${STEP},
  cols: ${cols},
  rows: ${rows},
  dots: '${d}',
};

/** lon/lat → map grid units */
export const project = (lon: number, lat: number) => ({
  x: (lon - MAP.lon0) / MAP.step,
  y: (MAP.lat0 - lat) / MAP.step,
});
`,
);
console.log(`${n} dots, ${cols + 1}×${rows + 1} grid, ${(d.length / 1024).toFixed(1)} KB path`);
